import type { Movie } from "./types";

// ---------------------------------------------------------------------------
// Rating scale: 2–5 in steps of 0.5. An empty rating means "not rated yet"
// (backlog entries have no rating).
// ---------------------------------------------------------------------------
export const MIN_RATING = 2;
export const MAX_RATING = 5;
export const RATING_STEP = 0.5;

export const RATING_OPTIONS: number[] = Array.from(
  { length: Math.round((MAX_RATING - MIN_RATING) / RATING_STEP) + 1 },
  (_, i) => MIN_RATING + i * RATING_STEP
);

/** "" (no rating) or one of the allowed steps. */
export function isValidRating(value: string): boolean {
  if (value.trim() === "") return true;
  return RATING_OPTIONS.includes(Number(value));
}

// ---------------------------------------------------------------------------
// Safe access to frontmatter. Notes are edited by hand in Obsidian, so a
// field that is normally a list can also be a single string, null or missing.
// ---------------------------------------------------------------------------
export function asArray(value: unknown): unknown[] {
  if (value === null || value === undefined || value === "") return [];
  return Array.isArray(value) ? value : [value];
}

export function getTags(movie: Movie): string[] {
  return asArray(movie.frontmatter?.tags).map(String);
}

export function getRating(movie: Movie): number | null {
  const value = Number(movie.rating);
  return movie.rating !== "" && movie.rating != null &&
    Number.isFinite(value) && value > 0 ? value : null;
}

export function isWatched(movie: Movie): boolean {
  return getRating(movie) !== null;
}

export function isBacklog(movie: Movie): boolean {
  return getRating(movie) === null && getTags(movie).includes("backlog");
}

const EARLIEST_YEAR = 1888; // first film ever made

/**
 * ISO dates (YYYY-MM-DD) from the `watched` list, e.g. "[[2014-01-09 Cz]]".
 * Dates with an implausible year (typos such as 2205) are ignored so a single
 * bad note cannot stretch the charts over hundreds of empty years.
 */
export function getWatchedDates(
  movie: Movie,
  maxYear: number = new Date().getFullYear() + 1
): string[] {
  return asArray(movie.frontmatter?.watched)
    .map(value => String(value).match(/\d{4}-\d{2}-\d{2}/)?.[0] ?? null)
    .filter((date): date is string => {
      if (date === null) return false;
      const year = Number(date.slice(0, 4));
      return year >= EARLIEST_YEAR && year <= maxYear;
    });
}

export function getLastWatched(movie: Movie): number {
  const times = getWatchedDates(movie)
    .map(date => new Date(date).getTime())
    .filter(Number.isFinite);
  return times.length ? Math.max(...times) : 0;
}

// ---------------------------------------------------------------------------
// File names
// ---------------------------------------------------------------------------

/**
 * Makes a title safe to use as a note file name. A "/" in a title would
 * otherwise create a sub-folder ("Face/Off" -> ".../Face/Off (1997).md"), and
 * Obsidian/Windows reject  \ / : * ? " < > |
 */
export function sanitizeFilename(title: string): string {
  const cleaned = title
    .replace(/\s*:\s*/g, " - ")
    .replace(/[\\/|]/g, "-")
    .replace(/[*?"<>]/g, "")
    .replace(/\s+/g, " ")
    .replace(/^[\s.]+|[\s.]+$/g, "");
  return cleaned;
}

// ---------------------------------------------------------------------------
// Optimistic changes.
//
// The index is regenerated by GitHub Actions and lags behind a save by a
// minute or more. After a successful write we remember the change locally
// (`pending`: path -> new Movie, or null for a deletion) and lay it over the
// index until the index catches up.
// ---------------------------------------------------------------------------
export type PendingChanges = Map<string, Movie | null>;

const collator = new Intl.Collator("pl");

export function applyPending(
  indexMovies: Movie[],
  pending: PendingChanges
): { movies: Movie[]; remaining: PendingChanges } {
  const byPath = new Map(indexMovies.map(movie => [movie.path, movie]));
  const remaining: PendingChanges = new Map(pending);

  for (const [path, change] of pending) {
    const indexed = byPath.get(path);

    if (change === null) {
      // Deletion: done once the file is gone from the index.
      if (indexed) byPath.delete(path);
      else remaining.delete(path);
    } else if (indexed && indexed.sha === change.sha) {
      // The index already contains exactly what we wrote.
      remaining.delete(path);
    } else {
      byPath.set(path, change);
    }
  }

  const movies = [...byPath.values()].sort((a, b) =>
    collator.compare(a.title, b.title) || a.path.localeCompare(b.path)
  );
  return { movies, remaining };
}

